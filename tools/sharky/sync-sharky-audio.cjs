'use strict';
/**
 * Sync the Sharky subfolder cues that tools/audio/sync-studio-audio.mjs does
 * not cover (it reads top-level one-shots, music/ and lanes/ only):
 *
 *   coin_key/      Rayman coin ladders in the loop key, k0/k2/k4 x 13, and the
 *                  octave-up Frenzy star-coin sets _f00..12 (design 8.3)
 *   graze/         sk_graze_loop 4 pitch steps (+0/+2/+4/+7 st)
 *   pass/          Doppler sk_pass_whoosh by speed band (stereo, R to L)
 *   gate_bonus/    Gate Bonus chime by multiplier tier
 *   music/states/  muffled and lift versions of the loop and its key variants
 *
 * One-shots become 16-bit PCM WAV (react-native-audio-api decodes WAV, not
 * AAC); music stays .m4a. Writes src/assets/games/audio/sharky/<sub>/ and
 * src/games/sharky/audio/sharkyAudio.dev.generated.ts. Every cue here is a
 * candidate pending Dustin's ear: src/games/sharky/audio/sharkyAudio.ts only
 * registers them in __DEV__; release builds fall back to Chris's sounds.
 *
 *   node tools/sharky/sync-sharky-audio.cjs [--src /path/to/tps-mg/audio]
 */
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '../..');
const argSrc = process.argv.indexOf('--src');
const SRC = path.resolve(argSrc >= 0 ? process.argv[argSrc + 1] : path.join(root, '../audio'), 'sharky');
const OUT = path.join(root, 'src/assets/games/audio/sharky');
const TS = path.join(root, 'src/games/sharky/audio/sharkyAudio.dev.generated.ts');

function wav(src, dst) {
  if (fs.existsSync(dst) && fs.statSync(dst).mtimeMs >= fs.statSync(src).mtimeMs) return;
  const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', src, '-c:a', 'pcm_s16le', '-ar', '44100', dst]);
  if (r.status !== 0) throw new Error(`ffmpeg failed for ${src}: ${r.stderr}`);
}

function durMs(file) {
  const r = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]);
  return Math.round(Number(String(r.stdout).trim()) * 1000) || undefined;
}

const cues = [];
const beds = [];
function ladder(id, sub, names, opts = {}) {
  fs.mkdirSync(path.join(OUT, sub), { recursive: true });
  const reqs = [];
  let dur;
  for (const n of names) {
    const src = path.join(SRC, sub, `${n}.m4a`);
    if (!fs.existsSync(src)) throw new Error(`missing ${src}`);
    const dst = path.join(OUT, sub, `${n}.wav`);
    wav(src, dst);
    dur = dur ?? durMs(src);
    reqs.push(`require('../../../assets/games/audio/sharky/${sub}/${n}.wav')`);
  }
  cues.push({ id, reqs, dur, ...opts });
}

const steps = Array.from({ length: 13 }, (_, i) => String(i).padStart(2, '0'));
for (const k of ['k0', 'k2', 'k4']) {
  ladder(`sk_coin_${k}`, 'coin_key', steps.map((s) => `coin_key_${k}_${s}`), { maxVoices: 3, cooldownMs: 0, group: 'coin' });
  ladder(`sk_coin_${k}_f`, 'coin_key', steps.map((s) => `coin_key_${k}_f${s}`), { maxVoices: 3, group: 'coin' });
}
ladder('sk_graze', 'graze', ['sk_graze_loop_p0', 'sk_graze_loop_p2', 'sk_graze_loop_p4', 'sk_graze_loop_p7'], { maxVoices: 1, gainDb: -8 });
ladder('sk_pass', 'pass', ['sk_pass_whoosh_band0', 'sk_pass_whoosh_band1', 'sk_pass_whoosh_band2'], { maxVoices: 1, cooldownMs: 250 });
ladder('sk_gate_bonus', 'gate_bonus', ['sk_gate_bonus_t0', 'sk_gate_bonus_t1', 'sk_gate_bonus_t2', 'sk_gate_bonus_t3'], { maxVoices: 1, priority: 2 });

fs.mkdirSync(path.join(OUT, 'music'), { recursive: true });
for (const key of ['', '_p2', '_p4']) {
  for (const st of ['muffled', 'lift']) {
    const n = `sharky_loop${key}_${st}`;
    const src = path.join(SRC, 'music/states', `${n}.m4a`);
    if (!fs.existsSync(src)) throw new Error(`missing ${src}`);
    const dst = path.join(OUT, 'music', `${n}.m4a`);
    fs.copyFileSync(src, dst);
    beds.push({ id: n, req: `require('../../../assets/games/audio/sharky/music/${n}.m4a')`, loopEndMs: durMs(src) });
  }
}

const lines = [];
lines.push('/* eslint-disable */');
lines.push('// AUTO-GENERATED by tools/sharky/sync-sharky-audio.cjs. Do not edit by hand.');
lines.push('// Candidates pending Dustin\'s ear (approved: false): registered in __DEV__ only.');
lines.push("import type { BedDef, CueDef } from '../../../gamekit/audio/chrisBank';");
lines.push('');
lines.push('export const SHARKY_EXTRA_CUES: Record<string, CueDef> = {');
for (const c of cues) {
  const extra = [
    c.dur ? `durationMs: ${c.dur}` : '',
    c.maxVoices ? `maxVoices: ${c.maxVoices}` : '',
    c.cooldownMs ? `cooldownMs: ${c.cooldownMs}` : '',
    c.gainDb ? `gainDb: ${c.gainDb}` : '',
    c.priority ? `priority: ${c.priority}` : '',
    c.group ? `group: '${c.group}'` : '',
  ].filter(Boolean).join(', ');
  lines.push(`  '${c.id}': { src: ${c.reqs[0]}, ladder: [${c.reqs.join(', ')}], ${extra}, approved: false },`);
}
lines.push('};');
lines.push('');
lines.push('export const SHARKY_EXTRA_BEDS: Record<string, BedDef> = {');
for (const b of beds) lines.push(`  '${b.id}': { src: ${b.req}, bpm: 136, beatsPerBar: 4, offsetMs: 0, loopEndMs: ${b.loopEndMs}, approved: false },`);
lines.push('};');
lines.push('');
fs.mkdirSync(path.dirname(TS), { recursive: true });
fs.writeFileSync(TS, lines.join('\n'));
console.log('synced', cues.length, 'ladder cues and', beds.length, 'music state beds');
